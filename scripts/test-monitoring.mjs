import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
    create table auth.users(id text,email text,created_at timestamptz default now(),last_sign_in_at timestamptz,email_confirmed_at timestamptz,banned_until timestamptz,raw_app_meta_data jsonb default '{}');
    create table auth.sessions(id text,user_id text,created_at timestamptz,updated_at timestamptz,not_after timestamptz,ip inet,user_agent text);
    create table auth.audit_log_entries(id text,created_at timestamptz,ip_address text,payload jsonb);
    create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint);`);
  await db.exec(await readFile('supabase/migrations/0001_masterclass.sql','utf8'));
  await db.exec(await readFile('supabase/migrations/0018_super_admin_monitoring.sql','utf8'));
  await db.exec(await readFile('supabase/migrations/0019_admin_operations.sql','utf8'));
  await db.exec(`insert into profiles(id) values('owner'); insert into auth.users(id,email) values('owner','owner@example.com');
    update auth.users set raw_app_meta_data='{"role":"editor","secret":"never expose"}' where id='owner';
    insert into billing_ledger(event_id,event,entity_id,amount,currency) values('one','payment.captured','pay_1',10000,'INR'),('retry','payment.captured','pay_1',10000,'INR'),('two','refund.processed','refund_1',2000,'INR');`);
  const snapshot=(await db.query('select super_admin_snapshot(30) as data')).rows[0].data;
  assert.equal(snapshot.counts.users,1);
  assert.equal(snapshot.revenue[0].gross,10000,'repeated capture events must not double revenue');
  assert.equal(snapshot.revenue[0].refunds,2000);
  assert(snapshot.events.some(e=>e.action==='access_changed'));
  assert(!JSON.stringify(snapshot).includes('never expose'));
  await db.exec(`insert into learning_presence(user_id,session_id,path,device) values('owner','00000000-0000-4000-8000-000000000001','/learning/lessons','Desktop');
    insert into learning_presence(user_id,session_id,path,device,last_seen_at) values('inactive','00000000-0000-4000-8000-000000000002','/learning','Desktop',now()-interval '3 minutes');
    insert into content_reports(user_id,path,reason,description) values('owner','/learning/lessons','incorrect','The example needs correction.');
    insert into monitor_events(kind,action,status,details) values('uptime','probe',200,'{}'),('uptime','probe',503,'{}');`);
  const operations=(await db.query('select super_admin_operations(30) as data')).rows[0].data;
  assert.equal(operations.liveCount,1,'expired heartbeat must not count as live');
  assert.equal(operations.openReports,1);
  assert.equal(operations.availability.percent,50);
  assert.equal(operations.availability.samples,2);
  await db.exec(`grant usage on schema public,auth to authenticated; set role authenticated;`);
  await assert.rejects(db.query('select super_admin_snapshot(30)'),/permission denied/);
  await assert.rejects(db.query('select super_admin_operations(30)'),/permission denied/);
  await assert.rejects(db.query('select * from learning_presence'),/permission denied/);
  await assert.rejects(db.query('select * from content_reports'),/permission denied/);
  await assert.rejects(db.query('select prune_monitoring()'),/permission denied/);
  await assert.rejects(db.query('select * from monitor_events'),/permission denied/);
  await assert.rejects(db.query("insert into monitor_events(kind,action) values('audit','forged')"),/permission denied/);
  await db.exec('reset role; set role service_role;');
  assert.equal((await db.query('select super_admin_snapshot(30) as data')).rows[0].data.counts.users,1);
  assert.equal((await db.query('select super_admin_operations(30) as data')).rows[0].data.openReports,1);
  console.log('PASS: monitoring migration, aggregates, payment deduplication, role audit, secret exclusion, authenticated denial and service-only RPC.');
} finally { await db.close(); }
