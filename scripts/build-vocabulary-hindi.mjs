/**
 * Build the Hindi gloss table for the English vocabulary handbook.
 *
 * The card's Hindi toggle only appears when the word has a gloss, so a word
 * missing from the authored files would silently lose its button. This build
 * therefore fails rather than emitting a partial table: every word in
 * `ENGLISH_EXAM_VOCABULARY` must be glossed, and every gloss must belong to a
 * word that is actually in it.
 *
 * Glosses are hand-authored, pipe-delimited, one per line, as `word|अर्थ`.
 *
 *   node scripts/build-vocabulary-hindi.mjs <scratch-dir>
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: build-vocabulary-hindi.mjs <scratch-dir>");

const SOURCE = "lib/pro-learn/english-exam-vocabulary.ts";
const TARGET = "lib/pro-learn/english-vocabulary-hindi.ts";

// Rows are not all single lower-case words: the imported business glossary
// carries acronyms ("KPI") and phrases ("market share"), and a pattern that
// missed those would drop them from the table without failing.
const words = [...readFileSync(SOURCE, "utf8").matchAll(/^ {4}\["([A-Za-z0-9][A-Za-z0-9 '’-]*)",/gm)].map(match => match[1]);

const glosses = new Map();
for (const file of readdirSync(dir).filter(name => /^hindi-\d+\.txt$/.test(name)).sort()) {
  for (const [index, line] of readFileSync(join(dir, file), "utf8").split("\n").entries()) {
    if (!line.trim()) continue;
    const parts = line.split("|");
    if (parts.length !== 2) throw new Error(`${file}:${index + 1} has ${parts.length} fields, expected 2`);
    const [word, hindi] = parts.map(part => part.trim());
    if (glosses.has(word)) throw new Error(`${file}:${index + 1} repeats "${word}"`);
    // Devanagari, not a romanisation: the toggle exists so a Hindi reader can
    // read Hindi, and transliterated English would defeat that.
    if (!/[ऀ-ॿ]/.test(hindi)) throw new Error(`${file}:${index + 1} "${word}" is not written in Devanagari`);
    glosses.set(word, hindi);
  }
}

const missing = words.filter(word => !glosses.has(word));
const extra = [...glosses.keys()].filter(word => !words.includes(word));
if (missing.length) throw new Error(`${missing.length} words have no Hindi gloss: ${missing.join(", ")}`);
if (extra.length) throw new Error(`${extra.length} glosses name a word the handbook does not have: ${extra.join(", ")}`);

const quote = text => JSON.stringify(text);
const rows = words.sort()
  .map(word => `  ${/^[a-z]+$/.test(word) ? word : quote(word)}: ${quote(glosses.get(word))},`)
  .join("\n");

writeFileSync(TARGET, `/**
 * The Hindi meaning of every word in the vocabulary handbook, in Devanagari.
 *
 * Generated by \`scripts/build-vocabulary-hindi.mjs\` from the hand-authored
 * gloss files — edit those and re-run it rather than editing this table, which
 * a rebuild overwrites wholesale.
 *
 * Kept beside the entries rather than inside them so the definition table stays
 * readable, and so a missing gloss is a lookup miss the build catches rather
 * than a silently shifted tuple.
 */
export const VOCABULARY_HINDI: Record<string, string> = {
${rows}
};
`, "utf8");

console.log(`wrote ${words.length} Hindi glosses to ${TARGET}`);
