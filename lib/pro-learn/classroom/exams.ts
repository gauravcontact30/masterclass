import type { AwsHighlight } from "../aws-highlights";

/**
 * An exam and what to study for it.
 *
 * Every exam leads with an overview card — pattern, eligibility, marking and
 * strategy — because a reader meeting an exam for the first time needs to know
 * what it *is* before any syllabus topic helps them. The overview is named
 * "<Exam> at a glance" so it sorts first and never collides with a topic name.
 */
type Exam = [exam: string, overview: string, topics: [name: string, summary: string][]];

const examGroup = (exams: Exam[]): AwsHighlight[] =>
  exams.flatMap(([exam, overview, topics]) => [
    { name: `${exam} at a glance`, category: exam, summary: overview },
    ...topics.map(([name, summary]) => ({ name, category: exam, summary })),
  ]);

