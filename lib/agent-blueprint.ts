/**
 * The "Build an agent with these APIs" blueprint on the API Docs page.
 *
 * Each mode is a complete, runnable codebase: one file per step plus the
 * project files. Every code line is authored together with its note, so the
 * comment column can never drift out of line with the code. Code targets
 * LangChain 1.x, LangGraph 1.x, Deep Agents 0.7 and the current LangSmith SDK.
 */

export type BlueprintMode = "single" | "multi";
type Line = readonly [code: string, note?: string];

export type BlueprintFile = {
  path: string;
  language: "python" | "text";
  /** Step that introduces this file; project files have none. */
  step?: number;
  lines: readonly Line[];
};

export type BlueprintStep = {
  num: number;
  tech: string;
  title: string;
  desc: string;
  file: string;
  apis: { name: string; pkg: string }[];
};

export type Blueprint = { folder: string; run: string; steps: BlueprintStep[]; files: BlueprintFile[] };

export const fileCode = (file: BlueprintFile) => file.lines.map(([code]) => code).join("\n");

